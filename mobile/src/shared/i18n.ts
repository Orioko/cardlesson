const localeCode = Localization.getLocales()[0]?.languageCode ?? 'ru';
const detectedLng = localeCode === 'en' ? 'en' : 'ru';

i18n.use(initReactI18next).init({
  resources,
  lng: detectedLng,
  fallbackLng: 'ru',
  interpolation: {
    escapeValue: false,
  },
});

void getAppLanguage().then((savedLanguage) => {
  if (i18n.language !== savedLanguage) {
    void i18n.changeLanguage(savedLanguage);
  }
});

export { i18n };
